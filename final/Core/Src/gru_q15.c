static inline q15_t clip_q15(float x) {
	if (x >= 1.0f)
		return 32767;
	if (x <= -1.0f)
		return -32768;
	return (q15_t)(x * 32768.0f);
}

// fast tanh
static inline float fast_tanh(float x) {
	if (x >= 4.97)
		return 1.0;
	else if (x <= -4.97)
		return -1.0;
	float x2 = x * x;
	float a = x * (135135.0f + x2 * (17325.0f + x2 * (378.0f + x2)));
	float b = 135135.0f + x2 * (62370.0f + x2 * (3150.0f + x2 * 28.0f));
	return a / b;
}
static inline float tanh_c3(float v) {
	const float c1 = 0.03138777F;
	const float c2 = 0.276281267F;
	const float c_log2f = 1.442695022F;
	v *= c_log2f;
	int intPart = (int)v;
	float x = (v - intPart);
	float xx = x * x;
	float v1 = c_log2f + c2 * xx;
	float v2 = x + xx * c1 * x;
	float v3 = (v2 + v1);
	*((int *)&v3) += intPart << 24;
	float v4 = v2 - v1;
	return (v3 + v4) / (v3 - v4);
}

// a stable tanh
static inline float tanh_stable(float x) {
	if (x >= 0) {
		float exp2x = exp(-2.0f * x);
		return -(1.0f - 2.0f / (1.0f + exp2x));
	} else {
		float exp2x = exp(2.0f * x);
		return -(2.0f / (1.0f + exp2x) - 1.0f);
	}
}

// a stable sigmoid
static inline float sigmoid_stable(float x) {
	if (x >= 0)
		return 1 / (1.0f + exp(-x));
	else {
		float expx = exp(x);
		return expx / (1 + expx);
	}
}

static float buffer_in[3 * HIDDEN_SIZE];
static float buffer_hidden[3 * HIDDEN_SIZE];
static float buffer[3 * HIDDEN_SIZE];

void gru_dsp_q15(
	float ax, float ay, q15_t hidden[LAYER_NUM][HIDDEN_SIZE], float output[2],
	q15_t hidden_next[LAYER_NUM][HIDDEN_SIZE]
) {
	q63_t dot_result;
	float dot_result_float;

	float *r = buffer;
	float *z = buffer + HIDDEN_SIZE;
	float *n = buffer + 2 * HIDDEN_SIZE;

	for (int i = 0; i < 3 * HIDDEN_SIZE; ++i) {
		// W_in \cdot x (dequantized)
		float input_acc =
			((float)weight_ih[i][0] * ax + (float)weight_ih[i][1] * ay) * weight_ih_scale;

		// buffer_in = W_in \cdot x + bias_ih (dequantized)
		buffer_in[i] = input_acc + (float)bias_ih[0][i] * bias_ih_scale;

		// W_hh[0] \cdot h[0]
		arm_dot_prod_q15(
			(q15_t *)weight_hh[0][i], (q15_t *)hidden[0], HIDDEN_SIZE, &dot_result
		);
		dot_result_float = ((float)dot_result / 32768.0f);

		// buffer_hidden = W_hh[0] \cdot h[0] (dequantized) + bias_hh (dequantized)
		buffer_hidden[i] =
			(dot_result_float * weight_hh_scale) + ((float)bias_hh[0][i] * bias_hh_scale);
	}

	for (int i = 0; i < 2 * HIDDEN_SIZE; ++i) {
		buffer[i] = sigmoid_stable(buffer_in[i] + buffer_hidden[i]);
	}

	for (int i = 0; i < HIDDEN_SIZE; i++) {
		n[i] = fast_tanh(
			buffer_in[i + 2 * HIDDEN_SIZE] + r[i] * buffer_hidden[i + 2 * HIDDEN_SIZE]
		);
	}

	// h_next = (1 - z) * n + z * h_prev
	for (int i = 0; i < HIDDEN_SIZE; ++i) {
		// Dequantize previous hidden state for the mix
		float h_prev_float = (float)hidden[0][i] / 32768.0f;

		float h_new = (1.0f - z[i]) * n[i] + z[i] * h_prev_float;

		// Re-quantize to q15
		hidden_next[0][i] = clip_q15(h_new);
	}

	for (int l = 1; l < LAYER_NUM; ++l) {
		for (int i = 0; i < 3 * HIDDEN_SIZE; ++i) {
			// W_ih[l-1] \cdot h_next[l-1]
			arm_dot_prod_q15(
				(q15_t *)weight_ih_layers[l - 1][i], (q15_t *)hidden_next[l - 1],
				HIDDEN_SIZE, &dot_result
			);
			dot_result_float = ((float)dot_result / 32768.0f);

			// buffer_in =  W_ih[l-1] \cdot h_next[l-1] (dequantized) + bias_ih
			// (dequantized)
			buffer_in[i] = (dot_result_float * weight_ih_layers_scale) +
						   ((float)bias_ih[l][i] * bias_ih_scale);

			// W_hh[l] \cdot h[l]
			arm_dot_prod_q15(
				(q15_t *)weight_hh[l][i], (q15_t *)hidden[l], HIDDEN_SIZE, &dot_result
			);
			dot_result_float = ((float)dot_result / 32768.0f);

			// buffer_hidden = W_hh[l] \cdot h[l] (dequantized) + bias_hh (dequantized)
			buffer_hidden[i] = (dot_result_float * weight_hh_scale) +
							   ((float)bias_hh[l][i] * bias_hh_scale);
		}

		for (int i = 0; i < 2 * HIDDEN_SIZE; ++i) {
			buffer[i] = sigmoid_stable(buffer_in[i] + buffer_hidden[i]);
		}

		for (int i = 0; i < HIDDEN_SIZE; i++) {
			n[i] = fast_tanh(
				buffer_in[i + 2 * HIDDEN_SIZE] + r[i] * buffer_hidden[i + 2 * HIDDEN_SIZE]
			);
		}

		// Compute Next Hidden State
		for (int i = 0; i < HIDDEN_SIZE; ++i) {
			// Dequantize previous hidden state for the mix
			float h_prev_float = (float)hidden[l][i] / 32768.0f;

			float h_new = (1.0f - z[i]) * n[i] + z[i] * h_prev_float;

			// Re-quantize to q15
			hidden_next[l][i] = clip_q15(h_new);
		}
	}

	for (int i = 0; i < 2; i++) {
		// bias = bias_output (dequantized)
		float bias = (float)bias_output[i] * output_bias_scale;

		// W_out \cdot h_next[LAYER_NUM - 1]
		arm_dot_prod_q15(
			(q15_t *)weight_output[i], (q15_t *)hidden_next[LAYER_NUM - 1], HIDDEN_SIZE,
			&dot_result
		);
		dot_result_float = ((float)dot_result / 32768.0f);

		// output = W_out \cdot h_next[L - 1] + bias
		output[i] = dot_result_float * output_weight_scale + bias;
	}
}

