static inline q15_t clip_q15(float x) {
    if (x >= 1.0f) return 32767;
    if (x <= -1.0f) return -32768;
    return (q15_t)(x / 32768.0f);
}

// https://math.stackexchange.com/a/3485944
static inline float tanh_c3(float v)
{
    const float c1 = 0.03138777F;
    const float c2 = 0.276281267F;
    const float c_log2f = 1.442695022F;
    v *= c_log2f;
    int intPart = (int)v;
    float x = (v - intPart);
    float xx = x * x;
    float v1 = c_log2f + c2 * xx;
    float v2 = x + xx * c1 * x;
    float v3 = (v2 + v1);
    *((int*)&v3) += intPart << 24;
    float v4 = v2 - v1;
    return (v3 + v4) / (v3 - v4);
}

void tanh_q15(q15_t * data, uint16_t size, uint16_t int_width)
{
    uint16_t  i = size;
    q15_t    *pIn = data;
    q15_t    *pOut = data;
    uint16_t  shift_size = 8 + 3 - int_width;
    uint32_t  bit_mask = 0x7FF >> int_width;
    uint32_t  full_frac = bit_mask + 1;

    while (i)
    {
        q15_t     out;
        q15_t     in = *pIn++;
        q15_t     frac = (uint32_t) in & bit_mask;
        q15_t     value = tanhTable_q15[__USAT(in >> shift_size, 8)];
        q15_t     value2 = tanhTable_q15[__USAT(1 + (in >> shift_size), 8)];

        /* doing the interpolation here for better accuracy */
        out = ((q31_t) (full_frac - frac) * value + (q31_t) value2 * frac) >> shift_size;

        *pOut++ = out;
        i--;
    }

}

static arm_matrix_instance_q15 mat_hh[LAYER_NUM] = {
    {HIDDEN_SIZE, HIDDEN_SIZE, (q15_t *) weight_hh[0]},
    {HIDDEN_SIZE, HIDDEN_SIZE, (q15_t *) weight_hh[1]},
};

static arm_matrix_instance_q15 mat_ih[LAYER_NUM - 1] = {
    {HIDDEN_SIZE, HIDDEN_SIZE, (q15_t *) weight_ih_layers[0]},
};

