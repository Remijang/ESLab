// a stable tanh
float tanh_stable(float x) {
	if (x >= 0) {
		float exp2x = exp(-2.0f * x);
		return -(1.0f - 2.0f / (1.0f + exp2x));
	} else {
		float exp2x = exp(2.0f * x);
		return -(2.0f / (1.0f + exp2x) - 1.0f);
	}
}

void rnn(
	float ax, float ay, float hidden[LAYER_NUM][HIDDEN_SIZE], float output[2],
	float hidden_next[LAYER_NUM][HIDDEN_SIZE]
) {
	for (int i = 0; i < HIDDEN_SIZE; i++) {
		hidden_next[0][i] = bias_hh[0][i] + bias_ih[0][i];	// bias_hh + bias_ih
		for (int j = 0; j < HIDDEN_SIZE; j++) {				// W_hh \cdot h
			hidden_next[0][i] += weight_hh[0][i][j] * hidden[0][j];
		}

		hidden_next[0][i] += weight_ih[i][0] * ax + weight_ih[i][1] * ay;  // W_in \cdot x
		hidden_next[0][i] = tanh(hidden_next[0][i]);
	}
	for (int l = 1; l < LAYER_NUM; l++) {
		for (int i = 0; i < HIDDEN_SIZE; i++) {
			hidden_next[l][i] = bias_hh[l][i] + bias_ih[l][i];	// bias_hh + bias_ih
			for (int j = 0; j < HIDDEN_SIZE; j++) {				// W_hh \cdot h
				hidden_next[l][i] += weight_hh[l][i][j] * hidden[l][j];
				hidden_next[l][i] +=
					weight_ih_layers[l - 1][i][j] * hidden_next[l - 1][j];
			}

			hidden_next[l][i] = tanh(hidden_next[l][i]);
		}
	}
	// determine the output
	output[0] = bias_output[0], output[1] = bias_output[1];
	for (int i = 0; i < HIDDEN_SIZE; i++) {
		output[0] += weight_output[0][i] * hidden_next[LAYER_NUM - 1][i];
		output[1] += weight_output[1][i] * hidden_next[LAYER_NUM - 1][i];
	}
}